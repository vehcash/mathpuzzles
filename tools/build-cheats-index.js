/* GENERATES js/cheats-index.js — the light list of cheat-sheet topics (name, icon, colours, blurb, formula count).
   cheatsheets.html loads only this list up front; each topic's formulas (cheats/<topic>.js) are fetched when the
   reader scrolls to it, opens it or searches. Run after editing cheats/*.js (tools/build-pages.js runs it too).
   Usage: node tools/build-cheats-index.js */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
// the order of the topics on the page
const ORDER = ['algebra', 'functions', 'geometry', 'trigonometry', 'analytic', 'space', 'vectors', 'complex',
  'limits', 'derivatives', 'integrals', 'combinatorics', 'probability', 'statistics', 'number', 'logic'];

function build() {
  const dir = path.join(ROOT, 'cheats');
  const extra = fs.readdirSync(dir).filter(f => f.endsWith('.js') && f !== 'symbols.js').map(f => f.slice(0, -3)).filter(id => !ORDER.includes(id)).sort();
  const ids = [...ORDER.filter(id => fs.existsSync(path.join(dir, id + '.js'))), ...extra];
  const topics = [];
  const ctx = { Cheats: { topic(t) { topics.push(t); }, tutor() {} }, String };
  ctx.window = ctx;
  vm.createContext(ctx);
  for (const id of ids) vm.runInContext(fs.readFileSync(path.join(dir, id + '.js'), 'utf8'), ctx, { filename: id + '.js' });
  const list = topics.map(t => ({ id: t.id, icon: t.icon, color: t.color, bg: t.bg, cat: t.cat || '', name: t.name, blurb: t.blurb,
    n: t.sections.reduce((a, s) => a + s.items.length, 0) }));
  const out = '/* GENERATED by tools/build-cheats-index.js — do not edit by hand. The cheat-sheet topics, without their formulas. */\n' +
    'window.CheatsIndex = ' + JSON.stringify(list, null, 1) + ';\n';
  fs.writeFileSync(path.join(ROOT, 'js', 'cheats-index.js'), out);
  return list;
}

module.exports = build;
if (require.main === module) { const l = build(); console.log('js/cheats-index.js:', l.length, 'topics,', l.reduce((a, t) => a + t.n, 0), 'formulas'); }
